#!/usr/bin/env python3
"""Build the ready-to-use files in release/ from skills/write-in-your-voice/.

  release/write-in-your-voice.zip   upload to Claude (Customize > Skills); the skill
                                    folder is the top level of the archive
  release/paste-into-chat.md        the whole skill as one file, for chats and agents
                                    that cannot load skill folders

Run "python3 package.py" after editing the skill. "python3 package.py --check" exits
with code 1 when release/ is out of date.
"""
import io
import sys
import zipfile
from pathlib import Path

SKILL = "write-in-your-voice"
root = Path(__file__).resolve().parent
src = root / "skills" / SKILL
release = root / "release"
FIXED_DATE = (2020, 1, 1, 0, 0, 0)  # constant timestamps: same input, same bytes


def skill_files():
    return [p for p in sorted(src.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"]


def build_zip():
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in skill_files():
            info = zipfile.ZipInfo(str(Path(SKILL) / path.relative_to(src)).replace("\\", "/"),
                                   FIXED_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())
    return buffer.getvalue()


def build_paste():
    text = (src / "SKILL.md").read_text(encoding="utf-8")
    body = text.split("---", 2)[2].lstrip("\n")  # drop the YAML frontmatter
    parts = ["<!-- Generated by package.py from skills/write-in-your-voice. Do not edit. -->\n",
             "Follow the instructions below for every writing request in this conversation. ",
             "They refer to reference files; those files are included after the main text.\n\n",
             body.rstrip() + "\n"]
    for ref in sorted((src / "references").glob("*.md")):
        parts.append(f"\n---\n\n<!-- references/{ref.name} -->\n\n")
        parts.append(ref.read_text(encoding="utf-8").rstrip() + "\n")
    return "".join(parts).encode("utf-8")


def main():
    if not (src / "SKILL.md").is_file():
        raise SystemExit(f"Cannot find {src / 'SKILL.md'}")
    outputs = {release / f"{SKILL}.zip": build_zip(), release / "paste-into-chat.md": build_paste()}
    if "--check" in sys.argv[1:]:
        stale = [p.name for p, data in outputs.items() if not p.is_file() or p.read_bytes() != data]
        if stale:
            print("out of date: " + ", ".join(stale) + " (run: python3 package.py)")
            raise SystemExit(1)
        print("release/ is up to date")
        return
    release.mkdir(exist_ok=True)
    for path, data in outputs.items():
        path.write_bytes(data)
        print(f"wrote {path.relative_to(root)} ({len(data):,} bytes)")
    with zipfile.ZipFile(release / f"{SKILL}.zip") as archive:
        names = archive.namelist()
    assert f"{SKILL}/SKILL.md" in names, names
    for name in names:
        print("  " + name)


if __name__ == "__main__":
    main()
